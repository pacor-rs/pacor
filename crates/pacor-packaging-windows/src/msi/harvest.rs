//! Turning a built application into WiX components.
//!
//! WiX wants one `<Component>` per file, each with a `Guid`, grouped in a
//! `<ComponentGroup>` a feature can pull in. `heat.exe` could do this, but a
//! deterministic id is more valuable than a harvester: `heat -gg` mints new
//! component GUIDs on every build, which breaks repairs and makes two builds of
//! the same application look like different products.
//!
//! The constraints below are not stylistic; each one was hit while building a
//! real installer (see `docs/MSI.md`):
//!
//! * identifiers may not exceed 72 characters (`CNDL1026`) and may only contain
//!   `[A-Za-z0-9_.]` — no hyphens;
//! * every component has to be reachable from a feature, or `light` reports an
//!   orphaned component (`LGHT0267`);
//! * `Source` must be reachable through a `candle` variable, so the generated
//!   file carries no machine-specific absolute path and the component GUIDs
//!   stay the same no matter where the project is checked out.

use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result};

use pacor_core::packaging::deterministic_uuid_v5;

/// Component group the payload components are collected in.
pub(super) const PAYLOAD_COMPONENT_GROUP: &str = "AppPayload";

/// WiX's identifier limit (`CNDL1026`).
const IDENTIFIER_MAX_LEN: usize = 72;

/// Room inside [`IDENTIFIER_MAX_LEN`] for the `f_` prefix, the separator and the
/// eight hex digits that disambiguate truncated names.
const IDENTIFIER_BASE_MAX_LEN: usize = 48;

/// Writes `<payload.wxs>` for everything below `source_dir`.
///
/// `product_id` keeps component GUIDs unique across products: two applications
/// that happen to ship `data/app.so` must not claim the same component.
pub(super) fn harvest(source_dir: &Path, product_id: &str) -> Result<String> {
    if !source_dir.is_dir() {
        return Err(pacor_core::error::PlatformError::FileNotFound {
            path: source_dir.to_path_buf(),
        }
        .into());
    }

    let mut harvester = Harvester {
        product_id,
        components: Vec::new(),
        empty_directories: Vec::new(),
    };

    let mut body = String::new();
    harvester.directory(source_dir, "", 3, &mut body)?;

    for directory in &harvester.empty_directories {
        tracing::warn!(
            directory = %directory,
            "empty directory is not part of the MSI: an empty directory needs its own component, \
             which would add a registry keypath for no content"
        );
    }

    let mut payload = String::new();
    payload.push_str("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    payload.push_str(
        "<!-- Generated by pacor from the build output; do not edit. -->\n\
         <Wix xmlns=\"http://schemas.microsoft.com/wix/2006/wi\">\n\
         \x20   <Fragment>\n\
         \x20       <DirectoryRef Id=\"INSTALLDIR\">\n",
    );
    payload.push_str(&body);
    payload.push_str(
        "        </DirectoryRef>\n\
         \x20   </Fragment>\n\
         \x20   <Fragment>\n",
    );
    payload.push_str(&format!(
        "        <ComponentGroup Id=\"{PAYLOAD_COMPONENT_GROUP}\">\n"
    ));
    for component in &harvester.components {
        payload.push_str(&format!(
            "            <ComponentRef Id=\"{component}\" />\n"
        ));
    }
    payload.push_str(
        "        </ComponentGroup>\n\
         \x20   </Fragment>\n\
         </Wix>\n",
    );

    tracing::debug!(
        components = harvester.components.len(),
        "Harvested the application into WiX components"
    );

    Ok(payload)
}

struct Harvester<'a> {
    product_id: &'a str,

    /// Component ids in document order, for the `<ComponentGroup>`.
    components: Vec<String>,

    /// Directories without any file below them, which cannot be expressed.
    empty_directories: Vec<String>,
}

impl Harvester<'_> {
    /// Emits one `<Directory>` per subdirectory and one `<Component>` per file.
    fn directory(
        &mut self,
        directory: &Path,
        relative: &str,
        indent: usize,
        out: &mut String,
    ) -> Result<()> {
        let padding = "    ".repeat(indent);
        let mut entries: Vec<PathBuf> = fs::read_dir(directory)
            .with_context(|| format!("failed to read {}", directory.display()))?
            .map(|entry| entry.map(|entry| entry.path()))
            .collect::<std::io::Result<_>>()
            .with_context(|| format!("failed to read {}", directory.display()))?;

        // A directory listing has no defined order; sorting is what makes the
        // generated file — and therefore the build — reproducible.
        entries.sort();

        let mut subdirectories = Vec::new();
        for path in entries {
            let name = path
                .file_name()
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default();
            let relative_path = if relative.is_empty() {
                name.clone()
            } else {
                format!("{relative}/{name}")
            };

            if path.is_dir() {
                subdirectories.push((path, name, relative_path));
            } else if path.is_file() {
                let component = self.component(&relative_path);
                self.components.push(component.clone());
                out.push_str(&format!(
                    "{padding}<Component Id=\"{component}\" Guid=\"{}\">\n",
                    self.guid(&relative_path)
                ));
                out.push_str(&format!(
                    "{padding}    <File Id=\"{component}\" Source=\"$(var.SourceDir)\\{}\" KeyPath=\"yes\" />\n",
                    xml_escape(&relative_path.replace('/', "\\"))
                ));
                out.push_str(&format!("{padding}</Component>\n"));
            }
        }

        for (path, name, relative_path) in subdirectories {
            // The subtree is rendered before anything is written: the decision to emit
            // the element at all depends on whether it has content, and opening it
            // first left an element that was never closed — not XML, which is why
            // `candle` refused every package whose build output held an empty directory.
            let mut child = String::new();
            self.directory(&path, &relative_path, indent + 1, &mut child)?;

            if child.is_empty() {
                // Directories reachable below it would have produced something.
                if !contains_file(&path)? {
                    self.empty_directories.push(relative_path.clone());
                }
                // Nothing to install, so nothing to install into: an empty element
                // would describe a directory MSI creates on demand anyway.
                continue;
            }

            let directory_id = self.component(&relative_path);
            out.push_str(&format!(
                "{padding}<Directory Id=\"{directory_id}\" Name=\"{}\">\n",
                xml_escape(&name)
            ));
            out.push_str(&child);
            out.push_str(&format!("{padding}</Directory>\n"));
        }

        Ok(())
    }

    /// Component id for `relative_path`: the (truncated) path plus eight hex
    /// digits of its GUID, so the id is unique, stable and within the limit.
    fn component(&self, relative_path: &str) -> String {
        let guid = self.guid(relative_path).replace(['{', '}', '-'], "");
        let mut base: String = relative_path
            .chars()
            .map(|character| {
                if character.is_ascii_alphanumeric() || character == '_' || character == '.' {
                    character
                } else {
                    '_'
                }
            })
            .collect();

        if base.len() > IDENTIFIER_BASE_MAX_LEN {
            // Keep the file name, which is the informative part.
            base = base
                .chars()
                .skip(base.len() - IDENTIFIER_BASE_MAX_LEN)
                .collect();
        }
        if !base.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_') {
            base.insert(0, '_');
        }

        let identifier = format!("f_{base}.{}", &guid[..8]);
        debug_assert!(identifier.len() <= IDENTIFIER_MAX_LEN, "{identifier}");
        identifier
    }

    /// Deterministic component GUID, derived from the product and the relative
    /// path (always with forward slashes, so a checkout on another host — or
    /// another separator — yields the same id).
    fn guid(&self, relative_path: &str) -> String {
        deterministic_uuid_v5(&format!("{}/{relative_path}", self.product_id))
    }
}

/// Whether `directory` contains any file, at any depth.
fn contains_file(directory: &Path) -> Result<bool> {
    let mut pending = vec![directory.to_path_buf()];

    while let Some(directory) = pending.pop() {
        for entry in fs::read_dir(&directory)
            .with_context(|| format!("failed to read {}", directory.display()))?
        {
            let path = entry?.path();
            if path.is_dir() {
                pending.push(path);
            } else if path.is_file() {
                return Ok(true);
            }
        }
    }

    Ok(false)
}

/// Escapes the five characters that cannot appear literally in XML.
pub(super) fn xml_escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

#[cfg(test)]
mod tests {
    use super::*;

    use std::fs;

    use tempfile::TempDir;

    const PRODUCT: &str = "{11111111-2222-3333-4444-555555555555}";

    fn payload(files: &[(&str, &str)]) -> (TempDir, String) {
        let temp = TempDir::new().unwrap();
        for (relative, contents) in files {
            let path = temp.path().join(relative);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, contents).unwrap();
        }

        let xml = harvest(temp.path(), PRODUCT).unwrap();
        (temp, xml)
    }

    #[test]
    fn every_file_becomes_one_component_with_a_file_keypath() {
        let (_temp, xml) = payload(&[("my_app.exe", "exe"), ("data/app.so", "so")]);

        assert_eq!(xml.matches("<Component Id=").count(), 2, "{xml}");
        assert_eq!(xml.matches("KeyPath=\"yes\"").count(), 2, "{xml}");
        // The executable sits in the install directory, the library in `data`.
        assert!(xml.contains("<DirectoryRef Id=\"INSTALLDIR\">"), "{xml}");
        assert!(xml.contains("<Directory Id=\"f_data."), "{xml}");
        assert!(
            xml.contains("Source=\"$(var.SourceDir)\\data\\app.so\""),
            "{xml}"
        );
        assert!(xml.contains("<ComponentGroup Id=\"AppPayload\">"), "{xml}");
    }

    /// `light` refuses to link a component no feature references.
    #[test]
    fn every_component_is_referenced_from_the_component_group() {
        let (_temp, xml) = payload(&[
            ("my_app.exe", "exe"),
            ("data/app.so", "so"),
            ("data/flutter_assets/AssetManifest.bin", "bin"),
        ]);

        let component_ids: Vec<&str> = xml
            .match_indices("<Component Id=\"")
            .map(|(index, pattern)| {
                let rest = &xml[index + pattern.len()..];
                &rest[..rest.find('"').unwrap()]
            })
            .collect();
        assert_eq!(component_ids.len(), 3, "{xml}");

        for id in component_ids {
            assert!(
                xml.contains(&format!("<ComponentRef Id=\"{id}\" />")),
                "{id} is not referenced: {xml}"
            );
        }
    }

    /// Identifiers have a hard limit and a restricted alphabet, and the file
    /// name has to survive truncation to stay readable.
    #[test]
    fn identifiers_stay_within_the_wix_limits() {
        let deep =
            "data/flutter_assets/packages/cupertino_icons/assets/CupertinoIcons.ttf".to_string();
        let (_temp, xml) = payload(&[(&deep, "ttf")]);

        let identifiers: Vec<String> = xml
            .match_indices("Id=\"")
            .map(|(index, pattern)| {
                let rest = &xml[index + pattern.len()..];
                rest[..rest.find('"').unwrap()].to_string()
            })
            .collect();

        for identifier in &identifiers {
            assert!(
                identifier.len() <= IDENTIFIER_MAX_LEN,
                "{identifier} is {} characters",
                identifier.len()
            );
            assert!(
                identifier
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.'),
                "{identifier}"
            );
            assert!(
                identifier.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_'),
                "{identifier}"
            );
        }

        // The disambiguator keeps long names apart even after truncation.
        let (_temp, other) = payload(&[
            (
                "data/flutter_assets/packages/cupertino_icons/assets/CupertinoIcons.ttf",
                "a",
            ),
            (
                "data/flutter_assets/packages/cupertino_icons/assets/CupertinoIcons.otf",
                "b",
            ),
        ]);
        assert_ne!(xml, other);
    }

    /// A component GUID must not change between builds, and must differ between
    /// products that ship the same file.
    #[test]
    fn component_guids_are_deterministic_and_product_specific() {
        let (_temp_a, xml_a) = payload(&[("my_app.exe", "exe")]);
        let (_temp_b, xml_b) = payload(&[("my_app.exe", "exe")]);
        assert_eq!(xml_a, xml_b, "the same input must render the same file");

        let temp = TempDir::new().unwrap();
        fs::write(temp.path().join("my_app.exe"), "exe").unwrap();
        let other_product = harvest(temp.path(), "{99999999-8888-7777-6666-555555555555}").unwrap();
        assert_ne!(xml_a, other_product, "component GUIDs must be per product");
    }

    /// Windows forbids `<`, `>` and `"` in file names, so the characters that
    /// realistically need escaping are `&` and `'`.
    #[test]
    fn names_with_xml_metacharacters_are_escaped() {
        let (_temp, xml) = payload(&[("data/a&b'c.dat", "x")]);

        assert!(xml.contains("a&amp;b&apos;c.dat"), "{xml}");
        assert!(!xml.contains("a&b'c.dat"), "{xml}");
    }

    #[test]
    fn empty_directories_are_reported_rather_than_silently_dropped() {
        let temp = TempDir::new().unwrap();
        fs::create_dir_all(temp.path().join("data/empty")).unwrap();
        fs::write(temp.path().join("my_app.exe"), "exe").unwrap();

        let xml = harvest(temp.path(), PRODUCT).unwrap();

        assert!(!xml.contains("data/empty"), "{xml}");
        assert!(!xml.contains("<Directory Id=\"f_data_empty"), "{xml}");
    }

    /// The element used to be opened before the subtree was rendered, and the branch
    /// that skips an empty directory left it unterminated — which is not XML, so
    /// `candle` rejected the whole file. Every opening tag now has its closing tag.
    #[test]
    fn an_empty_directory_does_not_leave_an_unclosed_element() {
        let temp = TempDir::new().unwrap();
        fs::create_dir_all(temp.path().join("data/empty")).unwrap();
        fs::create_dir_all(temp.path().join("data/nested/also-empty")).unwrap();
        fs::create_dir_all(temp.path().join("data/flutter_assets")).unwrap();
        fs::write(temp.path().join("my_app.exe"), "exe").unwrap();
        fs::write(temp.path().join("data/flutter_assets/app.so"), "so").unwrap();

        let xml = harvest(temp.path(), PRODUCT).unwrap();

        assert_eq!(
            xml.match_indices("<Directory ").count(),
            xml.match_indices("</Directory>").count(),
            "an unclosed element breaks the file: {xml}"
        );
        for empty in ["f_data_empty", "f_data_nested", "f_data_nested_also-empty"] {
            assert!(
                !xml.contains(empty),
                "{empty} has nothing to install: {xml}"
            );
        }
        assert!(xml.contains("f_data_flutter_assets"), "{xml}");
    }

    #[test]
    fn a_missing_build_output_is_an_error() {
        let temp = TempDir::new().unwrap();
        let error = harvest(&temp.path().join("missing"), PRODUCT).unwrap_err();

        assert!(error.to_string().contains("missing"), "{error}");
    }

    #[test]
    fn xml_escaping_covers_the_five_metacharacters() {
        assert_eq!(
            xml_escape("a&b<c>d\"e'f"),
            "a&amp;b&lt;c&gt;d&quot;e&apos;f"
        );
    }
}
